/** Supported languages. */
export const LANGUAGES = Object.freeze(['es', 'en', 'ca']);

/** Language used when the page language cannot be resolved. */
export const DEFAULT_LANGUAGE = 'es';

/**
 * Resolves the page language: first path segment (/es/…, /en/…, /ca/…), then the
 * `language` page metadata, then <html lang>, then DEFAULT_LANGUAGE.
 * @returns {string}
 */
export function getLanguage() {
  const [, segment] = window.location.pathname.split('/');
  if (LANGUAGES.includes(segment)) return segment;
  const meta = document.head.querySelector('meta[name="language"]');
  const found = [meta && meta.content, document.documentElement.lang]
    .map((value) => (value || '').toLowerCase().split(/[-_]/)[0])
    .find((value) => LANGUAGES.includes(value));
  return found || DEFAULT_LANGUAGE;
}

/**
 * Translates a vocabulary key into the page language.
 * @param {string} key i18n key, e.g. 'common.accessibility.next'
 * @param {string} [fallback] returned when the key does not exist (defaults to the key)
 * @returns {string}
 */
export function t(key, fallback) {
  const dictionary = DICTIONARY[getLanguage()] || {};
  if (Object.prototype.hasOwnProperty.call(dictionary, key)) return dictionary[key];
  return fallback !== undefined ? fallback : key;
}

/**
 * Replaces {0}, {1}… placeholders (AEM i18n format), e.g.
 * formatMessage(t('common.accessibility.item-progress'), 1, 4) -> '1 de 4'.
 * @param {string} message
 * @param {...(string|number)} args
 * @returns {string}
 */
export function formatMessage(message, ...args) {
  return String(message).replace(/\{(\d+)\}/g, (match, index) => (
    args[index] !== undefined ? String(args[index]) : match
  ));
}
